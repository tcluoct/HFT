int run_replay(const Config& cfg, const std::string& jnl_path) {
  InstrumentTable table;
  if (!load_sidecar(jnl_path, table)) return 1;

  JournalReader jr;
  if (!jr.open(jnl_path)) {
    logf("replay: cannot open journal %s\n", jnl_path.c_str());
    return 1;
  }
  if (jr.sealed() && !jr.verified()) {
    logf("replay: journal checksum FAILED — refusing to use it\n");
    return 1;
  }
  if (!jr.sealed())
    logf("replay: journal is UNSEALED (crashed session) — %llu envelopes recovered "
                 "from file size, no checksum to verify\n",
                 static_cast<unsigned long long>(jr.header().count));

  auto site = build_replay_site(cfg, table, jr.header().day);
  if (!site) {
    logf("replay: strategy configuration is invalid\n");
    return 1;
  }
  std::uint64_t injected = 0;
  for (const Envelope& e : jr.envelopes()) {
    if (e.origin == Origin::Source) ++injected;
    site->inject(e);
  }
  const std::uint64_t live_hash = jr.header().stream_hash;
  const std::uint64_t replay_hash = site->stream().stream_hash();
  std::printf("replay: %llu envelopes (%llu source) day %u\n",
              static_cast<unsigned long long>(jr.envelopes().size()),
              static_cast<unsigned long long>(injected), jr.header().day);
  std::printf("  live stream hash   %016llx\n", static_cast<unsigned long long>(live_hash));
  std::printf("  replay stream hash %016llx\n", static_cast<unsigned long long>(replay_hash));
  std::printf("  state hash         %016llx\n",
              static_cast<unsigned long long>(site->state_hash()));
  if (!jr.sealed()) {
    std::printf("replay of an unsealed journal: no recorded hash to compare — state above is "
                "the reconstruction at the crash point\n");
    return 0;
  }
  const bool ok = replay_hash == live_hash;
  std::printf("replay %s\n", ok ? "PASS — Derived stream regenerated byte-identically"
                                : "FAIL — components or config differ from the live run");
  return ok ? 0 : 1;
}

